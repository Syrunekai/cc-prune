def snapshot_paths(path: str) -> list[str]:
    found = [p for p in glob.glob(glob.escape(path) + ".snap*")
             if re.search(r"\.snap\d+$", p)]
    return sorted(found, key=lambda p: int(re.search(r"snap(\d+)$", p).group(1)))


def take_snapshot(path: str) -> tuple[int, str]:
    existing = snapshot_paths(path)
    n = 0 if not existing else int(re.search(r"snap(\d+)$", existing[-1]).group(1)) + 1
    dst = f"{path}.snap{n}"
    shutil.copy2(path, dst)
    return n, dst


def cmd_snapshots(args) -> None:
    snaps = snapshot_paths(args.path)
    if not snaps:
        print("no snapshots yet -- the first `clear` creates snap0 "
              "from the pristine file")
        return
    for p in snaps:
        print(f"  {os.path.basename(p):<52} {mb(os.path.getsize(p))}")
    print(f"\n  current  {os.path.basename(args.path):<52} {mb(os.path.getsize(args.path))}")


def cmd_restore(args) -> None:
    src = f"{args.path}.snap{args.n}"
    if not os.path.exists(src):
        sys.exit(f"no such snapshot: {src}")
    guard_live(args)
    load(src)

    if os.path.exists(args.path):
        _, keep = take_snapshot(args.path)
        print(f"current file saved -> {os.path.basename(keep)}")

    tmp = args.path + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as out, open(src, "rb") as inp:
        shutil.copyfileobj(inp, out)
    shutil.copymode(args.path if os.path.exists(args.path) else src, tmp)
    os.replace(tmp, args.path)
    print(f"restored {os.path.basename(src)} -> {os.path.basename(args.path)}")


