def cmd_strip_commands(args) -> None:
    recs = load(args.path)
    wanted = {c.lstrip("/").lower() for c in args.commands}

    def strings(rec):
        def walk(o):
            if isinstance(o, dict):
                if o.get("type") in THINKING:
                    return
                for k, v in o.items():
                    if isinstance(v, str):
                        yield o, k, v
                    else:
                        yield from walk(v)
            elif isinstance(o, list):
                for i, v in enumerate(o):
                    if isinstance(v, str):
                        yield o, i, v
                    else:
                        yield from walk(v)
        yield from walk(rec)

    hits = []
    for i, rec in enumerate(recs):
        for cont, key, val in strings(rec):
            if not STDOUT_RE.search(val):
                continue
            m = NAME_RE.search(val)
            named = m.group(1).lower() if m else "<orphan>"
            if args.orphans or named in wanted:
                hits.append((i, cont, key, named))

    if not hits:
        print("no local-command-stdout blocks matched.")
        print("try --orphans, or check: grep -c 'local-command-stdout' FILE")
        return

    if args.dry_run:
        per = Counter()
        for i, cont, key, named in hits:
            per[named] += len(STDOUT_RE.search(cont[key]).group(2))
        for k, v in per.most_common():
            print(f"  /{k:<16}{v:>10,} chars")
        print(f"\n  {len(hits)} blocks, {sum(per.values()):,} chars total")
        print("  (drop --dry-run to strip)")
        return

    guard_live(args)
    n, snap = take_snapshot(args.path)
    print(f"snapshot -> {os.path.basename(snap)}")

    spare = set()
    if args.keep_last:
        for name in {h[3] for h in hits}:
            for h in [x for x in hits if x[3] == name][-args.keep_last:]:
                spare.add((h[0], h[2]))

    uuids = [r.get("uuid") for r in recs]
    parents = [r.get("parentUuid") for r in recs]
    thinking = thinking_fingerprint(recs)

    freed = count = 0
    for i, cont, key, named in hits:
        if (i, key) in spare:
            continue
        before = cont[key]
        after, k = STDOUT_RE.subn(
            lambda m: m.group(1) + f"{PLACEHOLDER} {len(m.group(2))} chars"
            + m.group(3), before)
        if k:
            freed += len(before) - len(after)
            count += k
            cont[key] = after

    write_validated(recs, args.path, uuids, parents, thinking)

    print(f"stripped {count} stdout blocks, {freed:,} chars")
    print(f"kept the last {args.keep_last} of each command")
    print(f"rollback: cc_prune.py restore {os.path.basename(args.path)} {n}")


